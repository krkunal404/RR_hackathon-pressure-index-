import { useQuery } from '@tanstack/react-query'
import { AlertTriangle, CheckCircle2 } from 'lucide-react'
import { useState } from 'react'
import { Bar, BarChart, CartesianGrid, Legend, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import { Card, CardBody, CardHeader, ErrorState, Skeleton, Tabs } from '@/components/ui/primitives'
import { ChartTooltip, PageHeader } from '@/components/widgets'
import { api, type Json } from '@/lib/api'
import { cn, fmt } from '@/lib/utils'

function Check({ label, ok, detail }: { label: string; ok: boolean; detail: React.ReactNode }) {
  return (
    <div className="flex items-start gap-3 rounded-xl border border-line bg-panel-2/40 p-3">
      {ok ? <CheckCircle2 className="mt-0.5 h-5 w-5 shrink-0 text-emerald" /> : <AlertTriangle className="mt-0.5 h-5 w-5 shrink-0 text-gold" />}
      <div><div className="text-[13px] font-medium text-ink">{label}</div><div className="tabular text-[12px] text-dim">{detail}</div></div>
    </div>
  )
}

function rankColor(r: number) {
  if (r < 0) return 'bg-panel-2 text-faint'
  if (r <= 10) return 'bg-emerald/20 text-emerald'
  if (r <= 20) return 'bg-gold/15 text-gold'
  return 'bg-brand/15 text-brand-2'
}

export default function Validation() {
  const q = useQuery({ queryKey: ['validation'], queryFn: api.validation })
  const top = { batters: useQuery({ queryKey: ['top10', 'batters'], queryFn: () => api.top10('batters') }), bowlers: useQuery({ queryKey: ['top10', 'bowlers'], queryFn: () => api.top10('bowlers') }) }
  const [role, setRole] = useState<'batters' | 'bowlers'>('batters')
  if (q.error) return <ErrorState error={q.error} />
  if (!q.data) return <div className="space-y-4"><Skeleton className="h-60" /><Skeleton className="h-96" /></div>
  const { accounting_checks: k, sensitivity: sens, temporal_stability: ts, spot_check: sp, pressure_validity: pv } = q.data
  const mr = k.margin_reconstruction
  const names = (top[role].data ?? []).map((p) => p.name.split(' ').slice(-1)[0])
  const stab = ['batters', 'bowlers'].flatMap((r) => Object.entries(ts[r].component_spearman as Record<string, number>).map(([c, v]) => ({ role: r, component: c, rho: v })))

  return (
    <div className="space-y-6">
      <PageHeader eyebrow="Validation" title="Can these rankings be trusted?"
        desc="Independent accounting checks, leakage tests, a manual recount of the #1 players, sensitivity to every major assumption, and split-half stability. All of it is generated by the pipeline." />

      <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
        <Check label="Innings totals reproduce official margins" ok={mr.within_7 > 0.9} detail={`${mr.matches} matches · mean error ${fmt(mr.mean_error, 2)} runs · ${fmt(mr.within_3 * 100, 0)}% within 3 · ${fmt(mr.within_7 * 100, 0)}% within 7`} />
        <Check label="Legal-ball accounting" ok={k.illegal_counted_legal === 0 && k.wides_counted_as_ball_faced === 0} detail={`${k.illegal_counted_legal} illegal counted legal · ${k.wides_counted_as_ball_faced} wides as balls faced · ${fmt(k.share_overs_exactly_6_legal * 100, 1)}% overs have exactly 6`} />
        <Check label="Bowler attribution" ok={k.byes_charged_to_bowler === 0 && k.runouts_credited_to_bowler === 0} detail={`${k.byes_charged_to_bowler} byes charged · ${k.runouts_credited_to_bowler} run-outs credited · ${k.bowler_wkts_not_team_wkts} orphan wickets`} />
        <Check label="No leakage into pre-ball state" ok={k.leakage_runs_before_mismatch === 0 && k.leakage_wkts_before_mismatch === 0} detail={`${k.leakage_runs_before_mismatch} run / ${k.leakage_wkts_before_mismatch} wicket mismatches vs cumulative earlier balls · WP cross-fitted by match`} />
        <Check label={`Manual recount · ${sp.top_batter.name}`} ok={sp.top_batter.pipeline_runs === sp.top_batter.manual_runs && sp.top_batter.pipeline_balls === sp.top_batter.manual_balls} detail={`runs ${sp.top_batter.pipeline_runs} = ${sp.top_batter.manual_runs} · balls ${sp.top_batter.pipeline_balls} = ${sp.top_batter.manual_balls}`} />
        <Check label={`Manual recount · ${sp.top_bowler.name}`} ok={sp.top_bowler.pipeline_runs === sp.top_bowler.manual_runs && sp.top_bowler.pipeline_wkts === sp.top_bowler.manual_wkts} detail={`runs ${sp.top_bowler.pipeline_runs} = ${sp.top_bowler.manual_runs} · balls ${sp.top_bowler.pipeline_legal_balls} = ${sp.top_bowler.manual_legal_balls} · wkts ${sp.top_bowler.pipeline_wkts} = ${sp.top_bowler.manual_wkts}`} />
        <Check label="Decided games are not 'pressure'" ok={pv.decided_death_balls_pressure_share < 0.05} detail={`${fmt(pv.decided_death_balls_pressure_share * 100, 1)}% of ${pv.decided_death_balls.toLocaleString()} death balls with WP < 5% or > 95% are pressure, vs ${fmt(pv.death_over_pressure_share * 100, 0)}% of all death balls`} />
      </div>

      <Card>
        <CardHeader title="Sensitivity — where does each top-10 player land under alternative assumptions?" subtitle="Cell = rank under that scenario (green ≤ 10, amber ≤ 20, red > 20, grey = falls below the sample bar)"
          action={<Tabs value={role} onChange={setRole} items={[{ value: 'batters', label: 'Batters' }, { value: 'bowlers', label: 'Bowlers' }]} />} />
        <CardBody className="overflow-x-auto scroll-thin">
          <table className="w-full min-w-[900px] border-separate border-spacing-1 text-[12px]" data-testid="sensitivity-grid">
            <thead>
              <tr>
                <th className="text-left text-[10.5px] font-semibold uppercase tracking-wider text-faint">Scenario</th>
                <th className="text-[10.5px] text-faint">ρ</th><th className="text-[10.5px] text-faint">kept</th>
                {names.map((n) => <th key={n} className="text-[10.5px] font-semibold text-dim">{n}</th>)}
              </tr>
            </thead>
            <tbody>
              {sens.map((s: Json) => (
                <tr key={s.scenario}>
                  <td className="pr-3 text-dim"><span className="text-[10px] uppercase tracking-wider text-faint">{s.group}</span><br /><span className="text-ink">{s.scenario}</span></td>
                  <td className="tabular text-center font-semibold text-ink">{fmt(s[role].spearman, 2)}</td>
                  <td className="tabular text-center text-dim">{s[role].top10_overlap}/10</td>
                  {s[role].baseline_top10_ranks.map((r: number, i: number) => (
                    <td key={i} className={cn('tabular rounded-md py-1.5 text-center font-semibold', rankColor(r))}>{r < 0 ? 'n/e' : r}</td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </CardBody>
      </Card>

      <div className="grid gap-6 xl:grid-cols-2">
        <Card>
          <CardHeader title="Split-half stability (2022–24 vs 2025–26)" subtitle={`Rank correlation of ratings across eras: batters ρ = ${fmt(ts.batters.rating_spearman, 2)} (n=${ts.batters.players_in_both}), bowlers ρ = ${fmt(ts.bowlers.rating_spearman, 2)} (n=${ts.bowlers.players_in_both})`} />
          <CardBody className="h-72">
            <ResponsiveContainer>
              <BarChart data={['scoring', 'survival', 'economy', 'wickets', 'impact', 'uplift', 'consistency'].map((c) => ({
                component: c, batters: stab.find((x) => x.role === 'batters' && x.component === c)?.rho, bowlers: stab.find((x) => x.role === 'bowlers' && x.component === c)?.rho,
              }))} margin={{ left: -12, right: 8, top: 8 }}>
                <CartesianGrid vertical={false} />
                <XAxis dataKey="component" tickLine={false} axisLine={false} />
                <YAxis tickLine={false} axisLine={false} />
                <Tooltip content={<ChartTooltip formatter={(v) => v.toFixed(2)} />} />
                <Legend />
                <Bar dataKey="batters" name="Batters" fill="#f43f5e" radius={[4, 4, 0, 0]} />
                <Bar dataKey="bowlers" name="Bowlers" fill="#38bdf8" radius={[4, 4, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </CardBody>
        </Card>
        <Card>
          <CardHeader title="What this means" />
          <CardBody className="space-y-3 text-[13px] leading-relaxed text-dim">
            <p><b className="text-ink">Robust to modelling choices.</b> Rating weights, eligibility bars and competition weighting barely move the order (ρ ≥ 0.98). The pressure definition matters more (ρ 0.80–0.94), as it should, since it defines which balls count.</p>
            <p><b className="text-ink">Modest across eras.</b> Pressure performance persists only weakly from 2022–24 to 2025–26. Scoring and survival are the most persistent components. Uplift (“clutch”) and consistency barely persist, which is why shrinkage down-weights them automatically.</p>
            <p><b className="text-ink">Read ranks as bands.</b> Use P(top 10) and the 90% interval: players ranked about 8–15 are statistically close. The top of the bowling list is more settled than the top of the batting list.</p>
          </CardBody>
        </Card>
      </div>
    </div>
  )
}
